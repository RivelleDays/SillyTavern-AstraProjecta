import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import prettier from "prettier";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");
const sourcePath = path.join(
	repoRoot,
	"node_modules",
	"tailwindcss",
	"preflight.css",
);
const outputPath = path.join(
	repoRoot,
	"src",
	"styles",
	"generated",
	"tailwind-scoped-preflight.css",
);
const uiRootAttr = "data-astra-projecta-ui-root";
const uiRootSelector = `[${uiRootAttr}]`;
const checkMode = process.argv.includes("--check");

function uniqueSelectors(selectors) {
	const seen = new Set();
	const ordered = [];

	for (const selector of selectors) {
		if (!selector || seen.has(selector)) {
			continue;
		}

		seen.add(selector);
		ordered.push(selector);
	}

	return ordered;
}

function scopeSingleSelector(selector) {
	if (!selector || selector.includes("::backdrop")) {
		return [];
	}

	if (selector === "html" || selector === ":host") {
		return [uiRootSelector];
	}

	if (selector === "*") {
		return [uiRootSelector, `${uiRootSelector} *`];
	}

	if (selector.startsWith("::")) {
		return [
			`${uiRootSelector}${selector}`,
			`${uiRootSelector} ${selector}`,
		];
	}

	if (selector.startsWith(":")) {
		return [`${uiRootSelector} ${selector}`];
	}

	return [`${uiRootSelector} ${selector}`];
}

function buildGeneratedHeader() {
	return [
		"/*",
		" * This file is generated by scripts/generate-scoped-tailwind-preflight.mjs.",
		" * Do not edit manually.",
		" */",
		"",
	].join("\n");
}

async function generateScopedPreflight() {
	const sourceCss = await fs.readFile(sourcePath, "utf8");
	const root = postcss.parse(sourceCss, { from: sourcePath });

	root.walkRules((rule) => {
		const scopedSelectors = uniqueSelectors(
			postcss.list
				.comma(rule.selector)
				.flatMap((selector) => scopeSingleSelector(selector.trim())),
		);

		if (scopedSelectors.length === 0) {
			rule.remove();
			return;
		}

		rule.selector = scopedSelectors.join(",\n");
	});

	root.walkAtRules((atRule) => {
		if (atRule.nodes && atRule.nodes.length === 0) {
			atRule.remove();
		}
	});

	const prettierConfig = (await prettier.resolveConfig(outputPath)) ?? {};

	return prettier.format(
		`${buildGeneratedHeader()}${root.toString().trim()}\n`,
		{
			...prettierConfig,
			parser: "css",
		},
	);
}

async function main() {
	const generatedCss = await generateScopedPreflight();

	if (checkMode) {
		let currentCss = "";

		try {
			currentCss = await fs.readFile(outputPath, "utf8");
		} catch {
			currentCss = "";
		}

		if (currentCss !== generatedCss) {
			console.error(
				"Generated scoped Tailwind preflight is stale. Run `npm run generate:scoped-preflight`.",
			);
			process.exit(1);
		}

		return;
	}

	await fs.mkdir(path.dirname(outputPath), { recursive: true });
	await fs.writeFile(outputPath, generatedCss, "utf8");
}

await main();
